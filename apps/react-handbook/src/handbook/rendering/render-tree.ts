// Reads the DOM tree, a simplified render tree, and the matching style rules
// from a document the browser really parsed and styled (the parsing demo's
// iframe). The document is another realm: check nodeType, not instanceof.

export type TreeNode = {
  /** Child-index path from <html>, shared by both trees so a node can be selected in either. */
  path: string;
  label: string;
  kind: "element" | "text" | "pseudo";
  note?: string;
  children: TreeNode[];
};

const ELEMENT = 1;
const TEXT = 3;
const PARSER_ADDED = ["html", "head", "body", "tbody"];

function elementLabel(el: Element) {
  const id = el.id ? `#${el.id}` : "";
  const classes = [...el.classList].map((c) => `.${c}`).join("");
  return `<${el.localName}${id}${classes}>`;
}

function textLabel(text: string) {
  const trimmed = text.trim().replace(/\s+/g, " ");
  return `"${trimmed.length > 28 ? `${trimmed.slice(0, 27)}…` : trimmed}"`;
}

function isRenderedText(node: Node) {
  return node.nodeType === TEXT && (node.textContent ?? "").trim() !== "";
}

/** The DOM tree as parsed, marking elements the parser added because the source didn't write them. */
export function domTree(doc: Document, source: string): TreeNode {
  const lower = source.toLowerCase();
  function walk(el: Element, path: string): TreeNode {
    const children: TreeNode[] = [];
    el.childNodes.forEach((child, i) => {
      if (child.nodeType === ELEMENT) children.push(walk(child as Element, `${path}.${i}`));
      else if (isRenderedText(child)) children.push({ path: `${path}.${i}`, label: textLabel(child.textContent!), kind: "text", children: [] });
    });
    const added = PARSER_ADDED.includes(el.localName) && !lower.includes(`<${el.localName}`);
    return { path, label: elementLabel(el), kind: "element", note: added ? "added by the parser" : undefined, children };
  }
  return walk(doc.documentElement, "0");
}

function pseudo(el: Element, which: "::before" | "::after", path: string): TreeNode | null {
  const style = el.ownerDocument.defaultView!.getComputedStyle(el, which);
  if (style.content === "none" || style.content === "normal" || style.display === "none") return null;
  return { path: `${path}${which}`, label: `${which} ${style.content}`, kind: "pseudo", note: "generated by CSS, not in the DOM", children: [] };
}

/**
 * A simplified render tree: display:none subtrees are left out, display:contents
 * elements give their children to their parent, visibility:hidden boxes are
 * marked, and ::before/::after boxes are added.
 */
export function renderTree(doc: Document): TreeNode | null {
  const view = doc.defaultView!;
  function walk(el: Element, path: string): TreeNode[] {
    const style = view.getComputedStyle(el);
    if (style.display === "none") return [];
    const children: TreeNode[] = [];
    const before = pseudo(el, "::before", path);
    if (before) children.push(before);
    el.childNodes.forEach((child, i) => {
      if (child.nodeType === ELEMENT) children.push(...walk(child as Element, `${path}.${i}`));
      else if (isRenderedText(child)) children.push({ path: `${path}.${i}`, label: textLabel(child.textContent!), kind: "text", children: [] });
    });
    const after = pseudo(el, "::after", path);
    if (after) children.push(after);
    if (style.display === "contents") return children;
    const note = style.visibility === "hidden" ? "takes space, not painted (visibility: hidden)" : undefined;
    return [{ path, label: elementLabel(el), kind: "element", note, children }];
  }
  return walk(doc.documentElement, "0")[0] ?? null;
}

/** Whether a render tree has anything to show besides the empty <html> and <body> boxes. */
export function hasContent(node: TreeNode | null): boolean {
  if (!node) return false;
  return node.kind !== "element" || node.children.some(hasContent) || !["<html>", "<body>"].includes(node.label);
}

export function nodeAt(doc: Document, path: string): Element | null {
  const [, ...indexes] = path.split(".");
  let node: Node | undefined = doc.documentElement;
  for (const i of indexes) node = node?.childNodes[Number(i)];
  return node?.nodeType === ELEMENT ? (node as Element) : null;
}

export type MatchedRule = { selector: string; declarations: string };

function collect(rules: CSSRuleList, el: Element, out: MatchedRule[]) {
  for (const rule of rules) {
    if ("selectorText" in rule) {
      const styleRule = rule as CSSStyleRule;
      try {
        if (el.matches(styleRule.selectorText)) out.push({ selector: styleRule.selectorText, declarations: styleRule.style.cssText });
      } catch {
        // pseudo-element selectors can't be matched against an element
      }
    } else if ("media" in rule && "cssRules" in rule) {
      const media = rule as CSSMediaRule;
      if (el.ownerDocument.defaultView!.matchMedia(media.conditionText).matches) collect(media.cssRules, el, out);
    }
  }
}

/** Author rules that match the element (constructed and page style sheets), plus its style attribute. */
export function matchedRules(el: Element): MatchedRule[] {
  const doc = el.ownerDocument;
  const out: MatchedRule[] = [];
  for (const sheet of [...doc.adoptedStyleSheets, ...doc.styleSheets]) collect(sheet.cssRules, el, out);
  const inline = el.getAttribute("style");
  if (inline) out.push({ selector: "style attribute", declarations: inline });
  return out;
}
